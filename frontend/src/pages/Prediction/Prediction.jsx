import { useMemo, useState } from "react";
import { Sparkles, RotateCcw } from "lucide-react";
import FormField from "../../components/forms/FormField";
import PredictionResult from "../../components/cards/PredictionResult";
import { UnavailableState } from "../../components/common/StatePanel";
import { predictionFormSchema } from "../../data/projectData.js";
import { runPrediction } from "../../services/predictionService";

const sections = [
  {
    key: "customerInformation",
    title: "Customer Information",
    desc: "Demographic and financial details about the client",
    fields: predictionFormSchema.customerInformation,
  },
  {
    key: "campaignInformation",
    title: "Campaign Information",
    desc: "Details of the current marketing contact",
    fields: predictionFormSchema.campaignInformation,
  },
  {
    key: "previousCampaignInformation",
    title: "Previous Campaign Information",
    desc: "History from earlier campaigns",
    fields: predictionFormSchema.previousCampaignInformation,
  },
  {
    key: "economicContext",
    title: "Economic Context",
    desc: "Macroeconomic indicators at contact time",
    fields: predictionFormSchema.economicContext,
  },
];

export default function Prediction() {
  const fields = useMemo(
    () => sections.flatMap((section) => section.fields),
    []
  );

  const empty = useMemo(
    () => Object.fromEntries(fields.map((field) => [field.name, ""])),
    [fields]
  );

  const [values, setValues] = useState(empty);
  const [errors, setErrors] = useState({});
  const [status, setStatus] = useState("idle");
  const [result, setResult] = useState(null);

  const handleChange = (name, value) => {
    setValues((current) => ({
      ...current,
      [name]: value,
    }));

    setErrors((current) => ({
      ...current,
      [name]: undefined,
    }));
  };

  const validate = () => {
    const nextErrors = {};

    fields.forEach((field) => {
      if (values[field.name] === "") {
        nextErrors[field.name] = "This field is required";
      }
    });

    setErrors(nextErrors);

    return Object.keys(nextErrors).length === 0;
  };

  const handleSubmit = async (e) => {
    e.preventDefault();

    if (!validate()) {
      return;
    }

    setStatus("loading");
    setResult(null);

    try {
      const predictionResult = await runPrediction(values);

      setResult(predictionResult);
      setStatus("success");
    } catch (error) {
      console.error("Prediction failed:", error);
      setStatus("error");
    }
  };

  const reset = () => {
    setValues(empty);
    setErrors({});
    setStatus("idle");
    setResult(null);
  };

  return (
    <div>
      <div className="page-header">
        <h1>Customer Subscription Prediction</h1>
      </div>

      <form onSubmit={handleSubmit}>
        {sections.map((section) => (
          <div className="card form-section" key={section.key}>
            <div className="form-section__header">
              <h3>{section.title}</h3>
              <p>{section.desc}</p>
            </div>

            <div className="form-grid">
              {section.fields.map((field) => (
                <FormField
                  key={field.name}
                  field={field}
                  value={values[field.name]}
                  onChange={handleChange}
                  error={errors[field.name]}
                />
              ))}
            </div>
          </div>
        ))}

        <div
          style={{
            display: "flex",
            gap: 12,
            marginBottom: 32,
            flexWrap: "wrap",
          }}
        >
          <button
            type="submit"
            className={`btn btn-primary ${status === "loading" ? "btn-loading" : ""
              }`}
            disabled={status === "loading"}
            style={{ minWidth: 200 }}
          >
            <Sparkles size={16} />
            {status === "loading" ? "Predicting…" : "Run Prediction"}
          </button>

          <button
            type="button"
            className="btn btn-secondary"
            onClick={reset}
          >
            <RotateCcw size={15} />
            Reset Form
          </button>
        </div>
      </form>

      {status === "error" && (
        <div className="card">
          <UnavailableState
            title="Prediction unavailable"
            message="The trained model parameters could not be evaluated."
          />
        </div>
      )}

      {status === "success" && result && (
        <div className="section">
          <div className="section-title">
            <div>
              <h2>Prediction Result</h2>
              <div className="section-subtitle">
                Generated by the selected Gaussian Naive Bayes model.
              </div>
            </div>
          </div>

          <PredictionResult result={result} />
        </div>
      )}
    </div>
  );
}